#!/usr/bin/env python3
"""Build the datastore inventory.

The CISO's question is "which datastores hold patient data, and who asked for
them?". The request files answer the first half; git history answers the
second. One row per datastore.

Usage:
    inventory.py [--requests DIR] [--output FILE] [--repo-root DIR]
"""

from __future__ import annotations

import argparse
import pathlib
import subprocess
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
DEFAULT_REQUESTS = HERE.parent / "requests"
DEFAULT_OUTPUT = HERE.parent.parent.parent / "inventory" / "datastores.md"


def git(repo_root: pathlib.Path, *args: str) -> str:
    """Run git, returning stdout, or "" if git has nothing to say."""
    try:
        result = subprocess.run(
            ["git", *args],
            cwd=repo_root,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        return ""
    return result.stdout.strip() if result.returncode == 0 else ""


def requested_by(repo_root: pathlib.Path, path: pathlib.Path) -> tuple[str, str]:
    """Who added this request file, and when (ISO date).

    Uses the commit that ADDED the file, not the last one to touch it: the
    question is who asked for the datastore, not who last edited the YAML.
    """
    relative = path.relative_to(repo_root) if path.is_absolute() else path
    out = git(
        repo_root,
        "log",
        "--diff-filter=A",
        "--follow",
        "--format=%an%x09%ad",
        "--date=short",
        "-1",
        "--",
        str(relative),
    )
    if not out or "\t" not in out:
        return ("unknown", "unknown")
    author, _, date = out.partition("\t")
    return (author.strip() or "unknown", date.strip() or "unknown")


def normalise_leaves(value) -> str:
    if isinstance(value, bool):
        return "no" if value is False else str(value).lower()
    text = str(value).strip()
    return "no" if text.lower() in {"no", "false"} else text


def judgment_flag(request: dict) -> str:
    reasons = []
    if request.get("classification") == "unsure":
        reasons.append("classification unsure")
    leaves = normalise_leaves(request.get("data_leaves_meridian"))
    if leaves != "no":
        reasons.append(f"leaves to {leaves}")
    return "; ".join(reasons) if reasons else "-"


def collect(requests_dir: pathlib.Path, repo_root: pathlib.Path) -> list[dict]:
    rows = []
    for path in sorted(requests_dir.glob("*.yaml")):
        request = yaml.safe_load(path.read_text()) or {}
        author, date = requested_by(repo_root, path)
        rows.append(
            {
                "service": request.get("service", path.stem),
                "team": request.get("team", "unknown"),
                "classification": request.get("classification", "unknown"),
                "flag": judgment_flag(request),
                "requested_by": author,
                "requested_on": date,
            }
        )
    return rows


def render(rows: list[dict]) -> str:
    lines = [
        "# Datastore inventory",
        "",
        "Generated by `paths/compliant-datastore/scripts/inventory.py` from the",
        "request files and git history. Do not edit by hand.",
        "",
    ]

    if not rows:
        lines += ["No datastores have been requested yet.", ""]
        return "\n".join(lines)

    phi = sum(1 for r in rows if r["classification"] == "phi")
    unsure = sum(1 for r in rows if r["classification"] == "unsure")
    flagged = sum(1 for r in rows if r["flag"] != "-")
    lines += [
        f"{len(rows)} datastore{'' if len(rows) == 1 else 's'}: "
        f"{phi} classified `phi`, {unsure} `unsure`, "
        f"{flagged} awaiting a judgment call.",
        "",
        "| Service | Team | Classification | Judgment case | Requested by | Date |",
        "|---|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| `{row['service']}` | {row['team']} | `{row['classification']}` | "
            f"{row['flag']} | {row['requested_by']} | {row['requested_on']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--requests", type=pathlib.Path, default=DEFAULT_REQUESTS)
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--repo-root",
        type=pathlib.Path,
        default=pathlib.Path.cwd(),
        help="where to run git; defaults to the working directory",
    )
    parser.add_argument("--stdout", action="store_true", help="print instead of writing")
    args = parser.parse_args(argv)

    if not args.requests.is_dir():
        print(f"no requests directory at {args.requests}", file=sys.stderr)
        return 1

    markdown = render(collect(args.requests, args.repo_root.resolve()))

    if args.stdout:
        print(markdown, end="")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(markdown)
        print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
